/**
 * `yarn glyphs:generate` — the handful of glyphs kara's own components draw (a search field's magnifier, a row's
 * chevron, a stepper's plus and minus). Not an icon set: apps bring their own icons as SVGs. On iOS each glyph is the
 * SF Symbol named in `glyphs.json`, which the system already has; on Android it is the Material Symbol (Outlined, 400)
 * named there, written as a vector drawable into the module's resources, which Gradle merges into every app.
 *
 * Writes `android/src/main/res/drawable/kara_glyph_*.xml` and `src/glyphs.ts`; both are committed.
 */
import {execFileSync} from 'node:child_process'
import {mkdirSync, readdirSync, readFileSync, rmSync, writeFileSync} from 'node:fs'
import {createRequire} from 'node:module'
import path from 'node:path'

import {androidVectorDrawable, parseSvgIcon} from '@hzblj/kara-expo-plugin'

const ROOT = path.resolve(import.meta.dirname, '..')
const DRAWABLES = path.join(ROOT, 'android', 'src', 'main', 'res', 'drawable')
const PREFIX = 'kara_glyph_'
const require = createRequire(import.meta.url)
const symbols = path.join(path.dirname(require.resolve('@material-symbols/svg-400/package.json')), 'outlined')

/** `chevronDown` → `kara_glyph_chevron_down`. */
const resourceName = name => `${PREFIX}${name.replace(/[A-Z]/g, letter => `_${letter.toLowerCase()}`)}`

const glyphs = JSON.parse(readFileSync(path.join(ROOT, 'glyphs.json'), 'utf8'))

mkdirSync(DRAWABLES, {recursive: true})

for (const file of readdirSync(DRAWABLES)) {
  if (file.startsWith(PREFIX)) {
    rmSync(path.join(DRAWABLES, file))
  }
}

const entries = Object.entries(glyphs).sort(([a], [b]) => a.localeCompare(b))

for (const [name, {material}] of entries) {
  const icon = parseSvgIcon(path.join(symbols, `${material}.svg`))

  writeFileSync(path.join(DRAWABLES, `${resourceName(name)}.xml`), androidVectorDrawable(icon))
}

const lines = entries.map(([name, {ios}]) => `  ${name}: {android: '${resourceName(name)}', ios: '${ios}'},`)

writeFileSync(
  path.join(ROOT, 'src', 'glyphs.ts'),
  `import type {SFSymbol} from 'sf-symbols-typescript'

// Generated by \`yarn glyphs:generate\` from \`glyphs.json\` — edit that, not this.

/**
 * The glyphs kara's own components draw, per platform: an SF Symbol on iOS, a vector drawable this module ships on
 * Android (Material Symbols, Apache 2.0). Not an icon set for apps — those bring their own icons.
 */
export const GLYPHS = {
${lines.join('\n')}
} as const satisfies Record<string, {android: string; ios: SFSymbol}>

export type GlyphName = keyof typeof GLYPHS
`
)

execFileSync(
  path.join(ROOT, '..', '..', 'node_modules', '.bin', 'biome'),
  ['format', '--write', path.join(ROOT, 'src', 'glyphs.ts')],
  {
    stdio: 'ignore',
  }
)

console.log(`glyphs: ${entries.map(([name]) => name).join(', ')}`)
